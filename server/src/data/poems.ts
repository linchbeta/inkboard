export function poemAt(n: number, date: Date, festival?: string, all = false): Poem {
  if (festival && !all && n % 3 === 0) {
    const f = POEMS.find((p) => p.festival && festival.includes(p.festival.replace(/节$/, "")));
    if (f) return f;
  }
  const season = SEASON[date.getMonth()];
  const pool = all ? POEMS : POEMS.filter((p) => !p.festival && (!p.season || p.season === season));
  return pool[cycleIndex(n, pool.length, 11)];
}

export function poemOfDay(date: Date, festival?: string, skip = 0, all = false): Poem {
  if (festival && !skip && !all) {
    const f = POEMS.find((p) => p.festival && festival.includes(p.festival.replace(/节$/, "")));
    if (f) return f;
  }
  const season = SEASON[date.getMonth()];
  const pool = all ? POEMS : POEMS.filter((p) => !p.festival && (!p.season || p.season === season));
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
  return pool[(((day + skip) * 37) % pool.length + pool.length) % pool.length];
}
